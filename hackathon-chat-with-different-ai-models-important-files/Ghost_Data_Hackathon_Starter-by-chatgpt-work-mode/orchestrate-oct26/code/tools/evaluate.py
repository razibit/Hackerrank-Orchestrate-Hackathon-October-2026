"""Compare generated sample predictions with public labels; does not run an agent."""
import argparse
import json
from collections import Counter
from pathlib import Path
from contract import FIELDS, STEP_FIELDS,read_csv,evidence_times,validate

def main():
 root=Path(__file__).resolve().parents[2]
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('predictions',type=Path)
 p.add_argument('--dataset',type=Path,default=root/'dataset')
 p.add_argument('--report',type=Path,required=True)
 args=p.parse_args()
 header,pred=read_csv(args.predictions);gold=read_csv(args.dataset/'sample_output.csv')[1]
 requests=read_csv(args.dataset/'sample_deletion_requests.csv')[1]
 errors=[] if header==FIELDS else ['incorrect predictions header']
 if not errors:errors=validate(pred,requests,evidence_times(args.dataset))
 if errors:raise SystemExit('Invalid predictions:\n'+'\n'.join(errors))
 predicted={r['case_id']:r for r in pred}
 status_ok=sequence_ok=tp=pred_total=gold_total=field_ok=field_total=0;failures=[]
 def signature(s): return json.dumps(s,sort_keys=True,ensure_ascii=False)
 for row in gold:
  other=predicted[row['case_id']];a=json.loads(row['steps_json']);b=json.loads(other['steps_json'])
  status_ok+=row['deletion_status']==other['deletion_status'];sequence_ok+=a==b
  gold_steps=Counter(signature(s) for s in a);pred_steps=Counter(signature(s) for s in b)
  tp+=sum((gold_steps&pred_steps).values());pred_total+=len(b);gold_total+=len(a)
  for i in range(max(len(a),len(b))):
   for k in sorted(STEP_FIELDS):
    field_total+=1
    if i<len(a) and i<len(b) and a[i][k]==b[i][k]:field_ok+=1
  if a!=b or row['deletion_status']!=other['deletion_status']:failures.append(row['case_id'])
 def ratio(n,d):return f'{n/d:.4%} ({n}/{d})' if d else 'N/A (zero denominator)'
 report=f"""# Public sample evaluation

Generated by the comparison tool. These are public-sample results, not hidden-set accuracy.

- Status accuracy: {ratio(status_ok,len(gold))}
- Exact step precision: {ratio(tp,pred_total)}
- Exact step recall: {ratio(tp,gold_total)}
- Positional field accuracy: {ratio(field_ok,field_total)}
- Exact sequence accuracy: {ratio(sequence_ok,len(gold))}
- Cases with any mismatch: {', '.join(failures) or 'None'}

Exact step matching uses all seven fields, including step_no and evidence_id; duplicates count as a multiset. Positional field accuracy compares all seven fields at each position, with missing/extra steps counted as seven incorrect fields. Sequence accuracy compares the complete ordered parsed step arrays; status accuracy is separate. Object-key order and whitespace are ignored.

## Participant-created cases

Add the results of at least three independent synthetic end-to-end cases. See preparation/SYNTHETIC_CASES.md. Validator unit tests do not measure audit reasoning.

## Failures and improvements

Record reproduced failures, changes, before/after results, and unresolved limitations. Do not infer hidden-set performance from these 32 samples.
"""
 args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(report,encoding='utf-8');print(report)
if __name__=='__main__':main()
